def patch_channel_processor(original_script_path: str):
    """
    Verilen scriptteki 'get_youtube_stream_url' fonksiyonunu bu bypass fonksiyonuyla değiştirir.
    """
    with open(original_script_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Yedek al
    backup_path = original_script_path + ".backup"
    with open(backup_path, "w", encoding="utf-8") as f:
        f.write(content)

    # Fonksiyon değişimi
    new_func = """
def get_youtube_stream_url(youtube_url: str, quality: str) -> Optional[str]:
    \"\"\"Bypass fonksiyonu - palofsc tarafından eklendi\"\"\"
    return get_stream_url_with_bypass(youtube_url)
"""
    # Eski fonksiyonu bul ve değiştir (regex veya basit replace)
    import re
    pattern = r"def get_youtube_stream_url\([^)]+\):\s*.*?(?=\ndef|\Z)"
    replacement = new_func
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)

    with open(original_script_path, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"[PATCH] {original_script_path} başarıyla yamalandı. Yedek: {backup_path}")

