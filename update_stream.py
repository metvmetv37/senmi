COOKIE_FILE = "cookies.txt"
BROWSER = "chrome"  # chrome, firefox, brave, edge, opera
YT_DLP_CMD = "yt-dlp"

def get_fresh_cookies_from_browser(browser: str = BROWSER) -> bool:
    """
    Tarayıcıdan geçerli YouTube cookie'lerini çeker ve cookies.txt olarak kaydeder.
    """
    cmd = [
        YT_DLP_CMD,
        "--cookies-from-browser", browser,
        "--cookies", COOKIE_FILE,
        "--simulate",
        "https://www.youtube.com/watch?v=dQw4w9WgXcQ"
    ]
    try:
        subprocess.run(cmd, check=True, timeout=30, capture_output=True)
        print(f"[OK] {browser} üzerinden cookie'ler başarıyla çekildi.")
        return True
    except subprocess.CalledProcessError as e:
        print(f"[HATA] Tarayıcıdan cookie çekilemedi: {e.stderr.decode()}")
        return False
    except Exception as e:
        print(f"[HATA] Beklenmeyen hata: {e}")
        return False

def convert_cookies_to_netscape(cookie_dict: Dict[str, str], domain: str = ".youtube.com") -> str:
    """
    Dict formatındaki cookie'leri Netscape formatına çevirir.
    """
    lines = [
        "# Netscape HTTP Cookie File",
        "# http://curl.haxx.se/rfc/cookie_spec.html",
        "# This file was generated by palofsc cookie converter"
    ]
    for name, value in cookie_dict.items():
        lines.append(f"{domain}\tTRUE\t/\tFALSE\t0\t{name}\t{value}")
    return "\n".join(lines)

